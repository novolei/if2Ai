export const JIACHANG_LOCALES: JiaochangLocale[] = ['zh-CN', 'en-US', 'ja-JP', 'ko-KR']

export function normalizeJiaochangLocale(value: string | null | undefined): JiaochangLocale {
  if (value?.startsWith('en')) return 'en-US'
  if (value?.startsWith('ja')) return 'ja-JP'
  if (value?.startsWith('ko')) return 'ko-KR'
  return 'zh-CN'
}
